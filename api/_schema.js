// Lược đồ CSDL (idempotent). Thêm cột mới bằng "ALTER TABLE … ADD COLUMN IF NOT EXISTS" ở cuối, không sửa lệnh cũ.
// Email luôn lưu chữ thường. Vai trò admin không lưu ở đây: tính từ biến ADMIN_EMAILS.
module.exports = [
  `CREATE TABLE IF NOT EXISTS users (
    id BIGSERIAL PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL DEFAULT '',
    google_sub TEXT UNIQUE,
    role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'teacher')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login TIMESTAMPTZ)`,
  `CREATE TABLE IF NOT EXISTS teacher_tokens (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    refresh_enc TEXT NOT NULL,
    scopes TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `CREATE TABLE IF NOT EXISTS classes (
    id BIGSERIAL PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    gc_course_id TEXT,
    archived BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `CREATE TABLE IF NOT EXISTS class_members (
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    name TEXT NOT NULL DEFAULT '',
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    group_name TEXT NOT NULL DEFAULT '',
    added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (class_id, email))`,
  `CREATE INDEX IF NOT EXISTS class_members_user ON class_members(user_id)`,
  `CREATE INDEX IF NOT EXISTS class_members_email ON class_members(email)`,
  `CREATE TABLE IF NOT EXISTS assignments (
    id BIGSERIAL PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    lesson_id TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    week_label TEXT NOT NULL DEFAULT '',
    period_label TEXT NOT NULL DEFAULT '',
    open_at TIMESTAMPTZ,
    due_at TIMESTAMPTZ,
    gc_coursework_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `CREATE INDEX IF NOT EXISTS assignments_class ON assignments(class_id)`,
  `CREATE TABLE IF NOT EXISTS submissions (
    id BIGSERIAL PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'started' CHECK (status IN ('started', 'submitted')),
    notebook JSONB,
    runs_count INT NOT NULL DEFAULT 0,
    active_seconds INT NOT NULL DEFAULT 0,
    completed BOOLEAN NOT NULL DEFAULT false,
    best JSONB,
    robot_verified BOOLEAN NOT NULL DEFAULT false,
    first_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at TIMESTAMPTZ,
    UNIQUE (assignment_id, user_id))`,
  `CREATE TABLE IF NOT EXISTS runs (
    id BIGSERIAL PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ok BOOLEAN NOT NULL,
    completed BOOLEAN NOT NULL,
    metrics JSONB NOT NULL)`,
  `CREATE INDEX IF NOT EXISTS runs_submission ON runs(submission_id)`,
  `CREATE TABLE IF NOT EXISTS grades (
    submission_id BIGINT PRIMARY KEY REFERENCES submissions(id) ON DELETE CASCADE,
    scores JSONB NOT NULL,
    total NUMERIC(4,1) NOT NULL,
    comment TEXT NOT NULL DEFAULT '',
    graded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    graded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    pushed_gc_at TIMESTAMPTZ)`,
  `CREATE TABLE IF NOT EXISTS feedback (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    class_id BIGINT REFERENCES classes(id) ON DELETE SET NULL,
    lesson_id TEXT NOT NULL,
    rating INT CHECK (rating BETWEEN 1 AND 5),
    text TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `ALTER TABLE classes ADD COLUMN IF NOT EXISTS gc_course_name TEXT`,
  `ALTER TABLE assignments ADD COLUMN IF NOT EXISTS gc_link TEXT`,
  `ALTER TABLE assignments ADD COLUMN IF NOT EXISTS gc_topic TEXT`,
  `CREATE TABLE IF NOT EXISTS live (
    class_id BIGINT PRIMARY KEY REFERENCES classes(id) ON DELETE CASCADE,
    state JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  // giai đoạn 3: tự quản lý lớp (mã lớp, trả bài, bảng tin) + ảnh bài làm lưu trên Google Drive của giáo viên
  `ALTER TABLE classes ADD COLUMN IF NOT EXISTS join_code TEXT`,
  `ALTER TABLE classes ADD COLUMN IF NOT EXISTS join_open BOOLEAN NOT NULL DEFAULT true`,
  `ALTER TABLE classes ADD COLUMN IF NOT EXISTS drive_folder_id TEXT`,
  `ALTER TABLE classes ADD COLUMN IF NOT EXISTS drive_link TEXT`,
  `CREATE UNIQUE INDEX IF NOT EXISTS classes_join_code ON classes(join_code)`,
  `ALTER TABLE assignments ADD COLUMN IF NOT EXISTS instructions TEXT NOT NULL DEFAULT ''`,
  `ALTER TABLE assignments ADD COLUMN IF NOT EXISTS need_photo BOOLEAN NOT NULL DEFAULT false`,
  `ALTER TABLE assignments ADD COLUMN IF NOT EXISTS drive_folder_id TEXT`,
  `ALTER TABLE grades ADD COLUMN IF NOT EXISTS returned_at TIMESTAMPTZ`,
  `CREATE TABLE IF NOT EXISTS teacher_drive (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    root_folder_id TEXT NOT NULL,
    root_link TEXT,
    shared_with TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `CREATE TABLE IF NOT EXISTS attachments (
    id BIGSERIAL PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
    owner_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    drive_file_id TEXT NOT NULL,
    link TEXT,
    name TEXT NOT NULL DEFAULT '',
    mime TEXT NOT NULL DEFAULT '',
    size INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `CREATE INDEX IF NOT EXISTS attachments_submission ON attachments(submission_id)`,
  `CREATE TABLE IF NOT EXISTS announcements (
    id BIGSERIAL PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now())`,
  `CREATE INDEX IF NOT EXISTS announcements_class ON announcements(class_id)`
];
